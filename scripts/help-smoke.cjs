'use strict'
// Real Electron integration test, using a disposable profile and no HTTP server.
const { app, BrowserWindow, Menu, session } = require('electron')
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const root = path.resolve(__dirname, '..')
const appRoot = process.env.CYMD_TEST_APP || root
const output = path.join(root, 'output/help-smoke')
fs.mkdirSync(output, { recursive: true })
app.setPath('userData', fs.mkdtempSync(path.join(output, 'profile-')))
app.getAppPath = () => appRoot
const windows = []
const errors = []
app.on('browser-window-created', (_event, win) => {
  windows.push(win)
  win.webContents.on('console-message', (event) => {
    if (event.level === 'error' && !event.message.includes('Autofill.')) errors.push(event.message)
  })
})
const timer = setTimeout(() => { fs.writeFileSync(path.join(output, 'timeout.txt'),'timeout'); app.exit(2) }, 60000)
const pause = ms => new Promise(resolve => setTimeout(resolve, ms))
async function until(check, label) {
  for (let i = 0; i < 100; i++) { try { if (await check()) return } catch {} await pause(80) }
  throw new Error('Timeout: ' + label)
}
async function evaluate(win, code) { try { return await win.webContents.executeJavaScript(code, true) } catch(error) { throw new Error(code + ': ' + error.message) } }
function findMenu(label) {
  function visit(items) { for(const item of items) { if(item.label===label) return item; const child=item.submenu && visit(item.submenu.items); if(child) return child } }
  return visit(Menu.getApplicationMenu().items)
}
require(path.join(appRoot, 'electron/main.cjs'))
app.whenReady().then(async () => {
  try {
    await until(() => windows.find(w => w.webContents.getURL().includes('/dist/index.html')), 'editor')
    const editor = windows.find(w => w.webContents.getURL().includes('/dist/index.html'))
    await until(() => evaluate(editor, '!!document.querySelector(".cm-content")'), 'editor ready')
    // Force offline network in the documentation partition before opening it.
    session.fromPartition('persist:cymd-help').enableNetworkEmulation({ offline: true })
    await evaluate(editor, 'window.cymdNative.setLanguage("fr")')
    await evaluate(editor, 'window.cymdNative.openHelp("overview")')
    await until(() => windows.find(w => w.webContents.getURL().includes('/help/index.html')), 'help window')
    const help = windows.find(w => w.webContents.getURL().includes('/help/index.html'))
    assert.equal(new URL(help.webContents.getURL()).protocol, 'file:')
    assert.ok(help.webContents.getURL().includes('#/fr/overview'))
    await until(() => evaluate(help, '!!document.querySelector("[data-cydoc-id=interface]")'), 'image block')
    await evaluate(help, 'document.querySelector("[data-cydoc-id=interface]").scrollIntoView()')
    await until(() => evaluate(help, '!!document.querySelector(".cy-image img")?.naturalWidth'), 'local image')
    assert.equal(await evaluate(help, 'typeof window.cymdNative'), 'undefined')
    assert.equal(await evaluate(help, 'typeof require'), 'undefined')
    assert.ok(await evaluate(help, '!!document.querySelector(".diagram svg")'))
    await evaluate(help, 'document.querySelector("[data-action=in]").click(); document.querySelector("[data-action=expand]").click()')
    assert.ok(await evaluate(help, '!!document.querySelector(".media-expanded") && !document.fullscreenElement'))
    assert.notEqual(await evaluate(help, 'document.querySelector(".zoom-value").textContent'), '100%')
    help.webContents.sendInputEvent({ type:'keyDown', keyCode:'Escape' })
    help.webContents.sendInputEvent({ type:'keyUp', keyCode:'Escape' })
    await until(() => evaluate(help, '!document.querySelector(".media-expanded")'), 'Escape collapse')
    await evaluate(help, 'const s=document.querySelector(".locale-control select"); s.value="en"; s.dispatchEvent(new Event("change",{bubbles:true}))')
    await until(() => help.webContents.getURL().includes('#/en/overview'), 'English route')
    await until(() => evaluate(help, 'document.documentElement.lang==="en"'), 'English content')
    await evaluate(help, 'document.querySelector("[data-search]").click()')
    await until(() => evaluate(help, '!!document.querySelector(".search-dialog input")'), 'search dialog')
    await evaluate(help, 'const q=document.querySelector(".search-dialog input"); q.value="save"; q.dispatchEvent(new Event("input",{bubbles:true}))')
    await until(() => evaluate(help, '!!document.querySelector(".search-results a")'), 'search results')
    help.webContents.sendInputEvent({ type:'keyDown', keyCode:'Escape' })
    help.webContents.sendInputEvent({ type:'keyUp', keyCode:'Escape' })
    await evaluate(help, 'window.scrollTo(0,400)')
    const remembered = await evaluate(help, 'window.scrollY')
    await evaluate(help, 'document.querySelector("a[data-page=documents]").click()')
    await until(() => help.webContents.getURL().includes('/documents'), 'page link')
    await evaluate(help, 'document.querySelector("a[data-page=overview]").click()')
    await until(() => help.webContents.getURL().endsWith('/overview'), 'return link')
    await until(async () => Math.abs(await evaluate(help, 'window.scrollY') - remembered) < 2, 'reading position')
    await evaluate(editor, 'window.cymdNative.openHelp("split")')
    await until(() => help.webContents.getURL().includes('#/fr/editing/split'), 'contextual target')
    assert.ok(await evaluate(help, '!!document.getElementById("split")'))
    assert.equal(windows.filter(w => !w.isDestroyed() && w.webContents.getURL().includes('/help/index.html')).length, 1)
    await evaluate(editor, 'window.cymdNative.openHelp("interface")')
    await until(() => evaluate(help, '!!document.querySelector(".zoom-value") && document.querySelector(".zoom-value").textContent==="120%"'), 'media deep link')
    await evaluate(editor, 'window.cymdNative.openHelp("overview")')
    await until(() => evaluate(help, 'document.querySelector("h1")?.textContent.includes("Bienvenue")'), 'French overview')
    await pause(200)
    fs.writeFileSync(path.join(output,'manual-fr.png'),(await help.webContents.capturePage()).toPNG())
    findMenu('Images et médias').click()
    await until(() => help.webContents.getURL().includes('#/fr/media/images'), 'native help menu')
    await evaluate(editor, 'window.dispatchEvent(new KeyboardEvent("keydown",{key:"F1",shiftKey:true,bubbles:true,cancelable:true}))')
    await until(() => help.webContents.getURL().includes('#/fr/editing/live'), 'Shift+F1')
    await evaluate(editor, '[...document.querySelectorAll("button")].find(b=>b.getAttribute("aria-label")==="Documentation (F1)").click()')
    await until(() => help.webContents.getURL().includes('#/fr/overview'), 'toolbar help')
    await evaluate(editor, 'window.dispatchEvent(new KeyboardEvent("keydown",{key:"F1",bubbles:true,cancelable:true}))')
    await evaluate(editor, 'window.cymdNative.setLanguage("en");')
    await evaluate(editor, 'window.cymdNative.openHelp("overview")')
    await until(() => help.webContents.getURL().includes('#/en/overview'), 'app language to reader')
    await evaluate(help, 'document.querySelector("[data-cydoc-id=interface]").scrollIntoView()')
    await until(() => evaluate(help, '!!document.querySelector(".cy-image img")?.naturalWidth'), 'English local image')
    fs.writeFileSync(path.join(output,'manual-en.png'),(await help.webContents.capturePage()).toPNG())
    const web = new BrowserWindow({ show: false, width: 1100, height: 800, webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false } })
    await web.loadFile(path.join(appRoot, 'dist/index.html'))
    await until(() => evaluate(web, '!!document.querySelector(".cm-content")'), 'browser editor')
    await evaluate(web, '[...document.querySelectorAll("button")].find(b=>b.getAttribute("aria-label")==="Documentation (F1)").click()')
    await until(() => evaluate(web, '!!document.querySelector(".help-dialog[open]")'), 'browser help dialog')
    await until(() => web.webContents.mainFrame.frames.find(f => f.url.includes('/help/index.html')), 'help iframe')
    const frame = web.webContents.mainFrame.frames.find(f => f.url.includes('/help/index.html'))
    await until(() => frame.executeJavaScript('!!document.querySelector("h1")'), 'iframe reader')
    await evaluate(web, 'document.querySelector(".help-dialog-bar button").click()')
    assert.ok(await evaluate(web, '!document.querySelector(".help-dialog[open]")'))
    assert.deepEqual(errors, [])
    fs.writeFileSync(path.join(output,'result.json'),JSON.stringify({ok:true,fileUrl:true,offline:true,menu:true,toolbar:true,f1:true,context:true,localImages:true,diagram:true,zoom:true,escape:true,languages:true,search:true,browserDialog:true,readingPosition:true,appRoot:path.basename(appRoot)},null,2))
    clearTimeout(timer)
    for (const win of windows) if (!win.isDestroyed()) win.destroy()
    app.exit(0)
  } catch(error) {
    fs.writeFileSync(path.join(output,'result.json'),JSON.stringify({error:String(error.stack),errors},null,2))
    console.error(error)
    app.exit(1)
  }
})
