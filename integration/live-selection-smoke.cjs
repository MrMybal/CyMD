const {app,BrowserWindow}=require('electron')
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict')
app.setPath('userData',path.resolve('output/live-selection-profile'))
const wait=ms=>new Promise(r=>setTimeout(r,ms))
const timeout=setTimeout(()=>app.exit(2),30000)
app.whenReady().then(async()=>{
 let server,win
 try{
  const {createServer}=await import('vite');server=await createServer({server:{port:0,hmr:false}});await server.listen()
  win=new BrowserWindow({show:false,width:1100,height:950,webPreferences:{sandbox:true,contextIsolation:true}})
  const run=code=>win.webContents.executeJavaScript(code)
  await win.loadURL(server.resolvedUrls.local[0]+'integration/live-selection.html');await wait(600)
  const snapshot=()=>run('({text:document.querySelector(".cm-content").innerText,table:!!document.querySelector(".cm-lp-table"),height:document.querySelector(".cm-content").getBoundingClientRect().height})')
  const before=await snapshot();assert.ok(before.table);assert.ok(!before.text.includes('**'));assert.ok(!before.text.includes('https://example.com'))
  await run('testEditor.view.focus();testEditor.view.dispatch({selection:{anchor:0,head:testSource.length}})');await wait(100)
  assert.deepEqual(await snapshot(),before)
  await run('testEditor.view.dispatch({selection:{anchor:12}})');await wait(100)
  assert.deepEqual(await snapshot(),before)
  const coords=await run('(()=>{const c=document.querySelector("td").getBoundingClientRect();return {x:Math.round(c.x+5),y:Math.round(c.y+c.height/2),end:Math.round(c.right-3)}})()')
  win.webContents.sendInputEvent({type:'mouseDown',x:coords.x,y:coords.y,button:'left',clickCount:1})
  win.webContents.sendInputEvent({type:'mouseMove',x:coords.end,y:coords.y,button:'left'})
  win.webContents.sendInputEvent({type:'mouseUp',x:coords.end,y:coords.y,button:'left',clickCount:1})
  await wait(100)
  const selected=await run('getSelection().toString()');assert.ok(selected.includes('Alpha'),JSON.stringify(selected));assert.ok((await snapshot()).table)
  await run('testEditor.setLive(false)');assert.ok((await snapshot()).text.includes('**Bold**'))
  await run('testEditor.setLive(true)');assert.ok(!(await snapshot()).text.includes('**Bold**'))
  assert.equal(await run('testEditor.view.state.doc.toString()'),await run('testSource'))
  fs.writeFileSync('output/live-selection-result.json',JSON.stringify({ok:true,tableSelection:selected,stableMarkup:true}))
  clearTimeout(timeout);win.destroy();await server.close();app.exit(0)
 }catch(e){fs.writeFileSync('output/live-selection-result.json',JSON.stringify({error:String(e.stack)}));app.exit(1)}
})
